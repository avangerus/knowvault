package question

import "testing"

func TestSourceQuoteMapsWhitespaceBackToExactArtifact(t *testing.T) {
	source := "\u0414\u043e. \u041f\u0423\u0418\u0422 \u0441\u043e\u0437\u0434\u0430\u043d\u0430 \u0434\u043b\u044f \u0443\u043f\u0440\u0430\u0432\u043b\u0435\u043d\u0438\u044f\r\n\t\u0418\u0422-\u0438\u043d\u0444\u0440\u0430\u0441\u0442\u0440\u0443\u043a\u0442\u0443\u0440\u043e\u0439\u00a0\u041f\u0424\u0420. \u041f\u043e\u0441\u043b\u0435."
	quote := "\u041f\u0423\u0418\u0422 \u0441\u043e\u0437\u0434\u0430\u043d\u0430 \u0434\u043b\u044f \u0443\u043f\u0440\u0430\u0432\u043b\u0435\u043d\u0438\u044f \u0418\u0422-\u0438\u043d\u0444\u0440\u0430\u0441\u0442\u0440\u0443\u043a\u0442\u0443\u0440\u043e\u0439 \u041f\u0424\u0420."
	actual, ok := sourceQuote(source, quote)
	if !ok || actual != "\u041f\u0423\u0418\u0422 \u0441\u043e\u0437\u0434\u0430\u043d\u0430 \u0434\u043b\u044f \u0443\u043f\u0440\u0430\u0432\u043b\u0435\u043d\u0438\u044f\r\n\t\u0418\u0422-\u0438\u043d\u0444\u0440\u0430\u0441\u0442\u0440\u0443\u043a\u0442\u0443\u0440\u043e\u0439\u00a0\u041f\u0424\u0420." {
		t.Fatalf("wrong source span %q %v", actual, ok)
	}
	for _, item := range []struct{ source, quote string }{
		{"\u043b\u0438\u043c\u0438\u0442 850 \u043f\u043e\u043b\u044c\u0437\u043e\u0432\u0430\u0442\u0435\u043b\u0435\u0439", "\u043b\u0438\u043c\u0438\u0442 150000 \u043f\u043e\u043b\u044c\u0437\u043e\u0432\u0430\u0442\u0435\u043b\u0435\u0439"},
		{"\u043d\u0430\u0447\u0430\u043b\u043e \u043f\u0440\u043e\u043f\u0443\u0449\u0435\u043d\u043d\u044b\u0435 \u0441\u043b\u043e\u0432\u0430 \u043a\u043e\u043d\u0435\u0446", "\u043d\u0430\u0447\u0430\u043b\u043e \u043a\u043e\u043d\u0435\u0446"},
		{"\u041f\u0424\u0420; \u0437\u0430\u0442\u0435\u043c \u0421\u0424\u0420", "\u041f\u0424\u0420, \u0437\u0430\u0442\u0435\u043c \u0421\u0424\u0420"},
		{"\u0441\u0442\u0440\u043e\u043a\u0430\\\n\u0434\u0440\u0443\u0433\u0430\u044f", "\u0441\u0442\u0440\u043e\u043a\u0430 \u0434\u0440\u0443\u0433\u0430\u044f"},
		{"\u0438\u0441\u0445\u043e\u0434\u043d\u044b\u0439 \u0442\u0435\u043a\u0441\u0442", " \n "},
	} {
		if _, ok := sourceQuote(item.source, item.quote); ok {
			t.Fatalf("rewritten or empty quote accepted: %q", item.quote)
		}
	}
}
